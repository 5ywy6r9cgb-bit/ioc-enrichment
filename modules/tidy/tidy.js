'use strict';
/**
 * tidy.js — what is taking up room and doing no job, and where you are named.
 *
 * ─────────────────────────────────────────────────────────────────────────
 * TWO QUESTIONS, DELIBERATELY SEPARATE
 *
 *   SPACE     Files that exist for no reason: caches a tool regenerates,
 *             zero-byte remnants, an error page saved as though it were a
 *             document, the same capture written twice.
 *
 *   EXPOSURE  Where the OPERATOR is named in files that are not investigation
 *             material. A home directory in a committed path, a hostname in a
 *             pasted log, an email in a config. None of it is secret and all
 *             of it is identifying, which is a different problem.
 *
 * They are separate because the answers differ. Space is deleted. Exposure is
 * usually REDACTED IN A COPY -- the original stays, because a path inside your
 * own provenance ledger is doing a job.
 *
 * ─────────────────────────────────────────────────────────────────────────
 * THE RULE THAT MATTERS MOST
 *
 * Nothing recorded in the provenance ledger is ever proposed for deletion, at
 * any size, for any reason. An evidence store whose cleanup tool can reach
 * into it is not an evidence store. `--apply` acts only on categories marked
 * `safe`, and `safe` is false for anything the ledger has ever hashed.
 *
 * ─────────────────────────────────────────────────────────────────────────
 * WHY THE IDENTIFIERS ARE NOT WRITTEN DOWN HERE
 *
 * A scanner that hardcodes the name it is looking for has published that name
 * into the repository it was meant to protect, and into every clone of it.
 * So the patterns are built at RUN TIME from the machine: the username, the
 * home directory, the hostname, and anything the operator put in .env. This
 * file contains no personal data and cannot.
 */

const os = require('os');
const path = require('path');

/**
 * Classes of file that exist for no reason.
 *
 * `safe` means: regenerated on demand, or provably empty. Everything else is
 * REPORTED and never acted on, because "I do not recognise this" and "this is
 * disposable" are not the same statement.
 */
const JUNK = [
  {
    name: 'python bytecode',
    safe: true,
    why: 'regenerated by Python on the next import',
    test: (p) => /(^|\/)__pycache__(\/|$)/.test(p) || /\.pyc$/.test(p),
  },
  {
    name: 'macOS folder metadata',
    safe: true,
    why: 'Finder writes it again the moment you open the folder',
    test: (p) => /(^|\/)\.DS_Store$/.test(p),
  },
  {
    name: 'editor backup',
    safe: true,
    why: 'a stray save from an editor, not a file anything reads',
    test: (p) => /(~|\.swp|\.swo|\.orig|\.rej)$/.test(p),
  },
  // ORDER MATTERS, AND THIS RULE MUST COME BEFORE 'empty file'.
  // A zero-byte file inside node_modules matched the empty rule first and was
  // classified SAFE — so a sweep could delete pieces of an installed package.
  // The walk skips node_modules anyway, but a classifier that is only correct
  // because of where it happens to be called is a classifier waiting to be
  // called somewhere else.
  {
    name: 'node modules',
    safe: false,
    why: 'reinstallable with npm install, but deleting it breaks the desk '
      + 'until you do — decide deliberately, not in a sweep',
    test: (p) => /(^|\/)node_modules(\/|$)/.test(p),
  },
  {
    name: 'empty file',
    safe: true,
    why: 'zero bytes — it holds nothing',
    // .gitkeep is zero bytes ON PURPOSE: it is the only thing keeping an
    // otherwise-empty directory in git. Deleting it removes the folder.
    test: (p, st) => st && st.size === 0 && !/(^|\/)\.gitkeep$/.test(p),
  },
];

/** Which junk class a path belongs to, or null. */
function classify(relPath, stat) {
  for (const j of JUNK) {
    if (j.test(relPath, stat)) return { category: j.name, safe: j.safe, why: j.why };
  }
  return null;
}

/**
 * Directories a scan must not walk into.
 *
 * `.git` because rewriting history is not tidying. `evidence` because it is
 * the point of the whole system -- it is scanned for DUPLICATES separately,
 * with the ledger consulted, and never by this path.
 */
const SKIP_DIRS = new Set(['.git', 'evidence', 'node_modules']);

/**
 * Build the identifier patterns from this machine.
 *
 * Anything short or generic is dropped. A username of "m" or a hostname of
 * "localhost" would match half the repository and bury the real hits, and a
 * scanner whose output is mostly noise is a scanner nobody reads twice.
 */
function identifiers(env = {}) {
  // The stand-ins are bracketed on purpose. `$HOME` reads as a shell variable
  // that something downstream might expand, and a bare `OPERATOR` reads as a
  // real name. `[HOME]` cannot be mistaken for either — a redacted file should
  // be unmistakably redacted.
  //
  // They are also checked by the suite: a stand-in shaped like a real email or
  // a real path would put exactly the pattern this file exists to find INTO
  // this file, and into every clone of the repository.
  const out = [];
  // `strong` marks an identifier that cannot appear by accident: a full home
  // directory, a hostname, an email. A bare given name cannot make that claim
  // — see below.
  const add = (label, value, replacement, strong) => {
    const v = String(value || '').trim();
    if (v.length < 4) return;
    if (['user', 'users', 'home', 'root', 'admin', 'localhost'].includes(v.toLowerCase())) return;
    if (out.some((o) => o.value === v)) return;
    // ── A GIVEN NAME IS ALSO AN ENGLISH WORD ────────────────────────────
    //
    // On the first live run the username matched thirty-plus files: README.md,
    // crosslink.js, ioc_check.py, mail.js. None of them named the operator.
    // The username was a four-letter word that also appears in ordinary
    // prose — "mark the file", "bookmark", "watermark", "markdown" — so the
    // EXPOSURE half of the report was almost entirely noise, and a report that
    // is mostly noise gets skimmed once and then ignored.
    //
    // A short single word with no separator cannot be treated as a confident
    // identifier. It is still reported, because sometimes it IS the operator,
    // but it is reported separately and labelled, so the real hits stay
    // visible.
    const weak = !strong && !/[\s@./\\-]/.test(v) && v.length <= 8;
    out.push({ label, value: v, replacement, strong: Boolean(strong), weak });
  };

  const home = os.homedir();
  add('home directory', home, '[HOME]', true);
  const user = (os.userInfo && os.userInfo().username) || path.basename(home || '');
  add('username', user, '[OPERATOR]', false);
  add('hostname', os.hostname().replace(/\.local$/i, ''), '[DESK]', true);
  // Optional, and only if the operator chose to put them in .env.
  add('operator name', env.PRA_OPERATOR_NAME, '[OPERATOR]', false);
  add('operator email', env.PRA_OPERATOR_EMAIL || env.SEC_CONTACT, '[EMAIL]', true);
  return out;
}

/** Every line of `text` that names the operator. */
function findIdentifiers(text, ids) {
  const hits = [];
  const lines = String(text || '').split('\n');
  for (let i = 0; i < lines.length; i++) {
    for (const id of ids) {
      if (!lines[i].includes(id.value)) continue;
      // A weak identifier must at least stand as its own word. Without this,
      // a username of "Mark" matches "markdown", "bookmark" and "watermark",
      // which is how one live run produced thirty files that named nobody.
      if (id.weak) {
        const bounded = new RegExp(`(^|[^A-Za-z0-9])${
          id.value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}([^A-Za-z0-9]|$)`);
        if (!bounded.test(lines[i])) continue;
      }
      hits.push({
        line: i + 1,
        label: id.label,
        weak: Boolean(id.weak),
        text: lines[i].trim().slice(0, 120),
      });
    }
  }
  return hits;
}

/** Replace every identifier with its stand-in. Used for a COPY, never in place. */
function redact(text, ids) {
  let out = String(text || '');
  // Longest first, and this is not a nicety. A home directory CONTAINS the
  // username, so replacing the username first turns the path into a hybrid --
  // half real prefix, half stand-in -- which the home-directory rule then no
  // longer matches. The result is a file marked redacted with the operator's
  // directory layout still legible in it, which is worse than not redacting,
  // because it gets handed out.
  //
  // (The example is described rather than written, because the suite refuses
  // any path-shaped or email-shaped literal in this file. A pattern in a
  // comment still ships to every clone of the repository.)
  for (const id of [...ids].sort((a, b) => b.value.length - a.value.length)) {
    out = out.split(id.value).join(id.replacement);
  }
  return out;
}

/** Bytes, for a human. */
function humanSize(n) {
  if (n < 1024) return `${n} B`;
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(0)} KB`;
  if (n < 1024 * 1024 * 1024) return `${(n / 1024 / 1024).toFixed(1)} MB`;
  return `${(n / 1024 / 1024 / 1024).toFixed(2)} GB`;
}

module.exports = {
  JUNK, SKIP_DIRS, classify, identifiers, findIdentifiers, redact, humanSize,
};
